package de.fraunhofer.aisec.cpg.frontends.csharp.statementhandler

import de.fraunhofer.aisec.cpg.frontends.csharp.CSharpLanguage
import de.fraunhofer.aisec.cpg.graph.*
import de.fraunhofer.aisec.cpg.graph.expressions.*
import de.fraunhofer.aisec.cpg.test.*
import java.nio.file.Path
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertIs
import kotlin.test.assertNotNull

class EmptyStatementTest : BaseTest() {

    /** An empty statement does nothing, but it still has to be part of the control flow. */
    @Test
    fun testEmptyStatement() {
        val topLevel = Path.of("src", "test", "resources", "csharp")
        val tu =
            analyzeAndGetFirstTU(
                listOf(topLevel.resolve("EmptyStatement.cs").toFile()),
                topLevel,
                true,
            ) {
                it.registerLanguage<CSharpLanguage>()
            }
        assertNotNull(tu)

        val method = tu.methods["Empty"]
        assertNotNull(method)
        val body = method.body
        assertIs<Block>(body)
        assertEquals(2, body.statements.size)

        // ;
        assertIs<Empty>(body.statements.firstOrNull())

        // return a;
        val ret = body.statements.getOrNull(1)
        assertIs<Return>(ret)
        assertRefersTo(ret.returnValue, method.parameters["a"])
    }
}
